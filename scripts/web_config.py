"""Write apps/web/lib/deployment.ts from networks/diana.toml and packages/abi, so the web reads the same deployment."""

import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    d = tomllib.loads((ROOT / "networks/diana.toml").read_text())
    abis = {n: json.loads((ROOT / "packages/abi" / f"{n}.json").read_text())
            for n in ("JobMarket", "NodeRegistry", "Competitions")}
    out = ["// Generated by scripts/web_config.py from networks/diana.toml and packages/abi. Do not edit.",
           f"export const deployment = {json.dumps({**d['contracts'], **d['roles']}, indent=2)} as const;"]
    for n, a in abis.items():
        out.append(f"export const {n[0].lower() + n[1:]}Abi = {json.dumps(a)} as const;")
    (ROOT / "apps/web/lib/deployment.ts").write_text("\n".join(out) + "\n")
    print("wrote apps/web/lib/deployment.ts")


if __name__ == "__main__":
    main()
