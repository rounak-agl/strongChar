"""Vectors that pin the browser's job preparation to the Python code, byte for byte.

Writes:
  vectors/web/prepare.json      a few CSVs (header, classification, regression, odd row counts) and every value the
                                owner derives from them: dataset and spec hashes, shard and validation hashes, the
                                initial weights hash, the shard table hash, the budget and the holdout hash
  apps/web/lib/browser/normals.ts  the first standard normals of numpy's default_rng(0): the initial weights are
                                    exactly sqrt(2/fan_in) times these, so the browser needs no port of PCG64

The browser test (apps/web/scripts/prepare-check.mjs) recomputes everything from the CSVs and compares.
Usage: uv run python scripts/web_vectors.py
"""

from __future__ import annotations

import base64
import json
import math
from pathlib import Path

import numpy as np
from eth_utils import keccak
from strongchar_core import encodings as enc
from strongchar_datasets.shards import cut
from strongchar_runtime.owner import plan
from strongchar_workloads.mlp import MLPExact

ROOT = Path(__file__).resolve().parents[1]
MAX_D_IN, HIDDEN, MAX_OUT = 256, 16, 100
N_NORMALS = MAX_D_IN * HIDDEN + HIDDEN * MAX_OUT


def csv_case(seed: int, rows: int, cols: int, task: str, header: bool) -> str:
    rng = np.random.default_rng(seed)
    x = rng.normal(0, 1, (rows, cols)) * rng.uniform(0.5, 40, cols) + rng.uniform(-5, 60, cols)
    x[:, 0] = np.round(x[:, 0])  # an integer-looking column, like age
    if task == "classification":
        y = (x @ rng.normal(0, 1, cols) > 0).astype(int) + (rng.random(rows) > 0.8).astype(int)
    else:
        y = x @ rng.normal(0, 0.1, cols) + rng.normal(0, 0.5, rows)
    lines = [",".join([f"f{i}" for i in range(cols)] + ["target"])] if header else []
    for r in range(rows):
        vals = [repr(float(v)) if c % 2 else f"{v:.6g}" for c, v in enumerate(x[r])]
        lines.append(",".join(vals + [str(int(y[r])) if task == "classification" else f"{y[r]:.5f}"]))
    return "\n".join(lines) + "\n"


CASES = [
    {"name": "health-like, header, 3 classes", "seed": 1, "rows": 1000, "cols": 6, "task": "classification", "header": True,
     "rounds": 2, "shards": 4, "quorum": 2},
    {"name": "no header, 1237 rows, 5 shards", "seed": 12, "rows": 1237, "cols": 9, "task": "classification", "header": False,
     "rounds": 3, "shards": 5, "quorum": 3},
    {"name": "regression", "seed": 3, "rows": 1100, "cols": 4, "task": "regression", "header": True,
     "rounds": 1, "shards": 3, "quorum": 2},
]


def main() -> None:
    out = []
    for c in CASES:
        text = csv_case(c["seed"], c["rows"], c["cols"], c["task"], c["header"])
        p = plan(text, rounds=c["rounds"], shards=c["shards"], quorum=c["quorum"])
        pieces = cut(p.data, p.split)
        ha, hn = p.split.holdout
        holdout = p.data.x[ha:ha + hn].tobytes() + p.data.y[ha:ha + hn].tobytes()
        out.append({
            **{k: c[k] for k in ("name", "rounds", "shards", "quorum")},
            "csv": text,
            "datasetHash": p.data.card.hash,
            "task": p.data.card.task, "classes": p.data.card.classes, "dIn": p.data.card.x_shape[0],
            "split": {"train": list(p.split.train), "val": list(p.split.val), "holdout": list(p.split.holdout),
                      "shards": [list(s) for s in p.split.shards]},
            "spec": p.spec.raw, "specHash": "0x" + p.spec.hash.hex(),
            "initialWeightsHash": "0x" + p.spec.initial_weights_hash().hex(),
            "shardTableHash": "0x" + enc.shard_table_hash(p.spec.shards).hex(),
            "shardHashes": ["0x" + keccak(b).hex() for b in pieces["train"]],
            "valHash": "0x" + keccak(pieces["val"][0]).hex(),
            "holdoutHash": "0x" + keccak(holdout).hex(),
            "opsPerRound": p.ops_per_round, "budget": p.budget, "refWork": p.ref_work, "maxNodes": p.max_nodes,
        })
    path = ROOT / "vectors/web/prepare.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(out, indent=1) + "\n")

    z = np.random.default_rng(0).standard_normal(N_NORMALS)
    for d, o in [(6, 3), (MAX_D_IN, MAX_OUT)]:  # the identity the browser relies on, checked before writing
        w = MLPExact(d, o, hidden=HIDDEN).init(0)
        alt = np.concatenate([math.sqrt(2 / d) * z[:d * HIDDEN], np.zeros(HIDDEN),
                              math.sqrt(2 / HIDDEN) * z[d * HIDDEN:d * HIDDEN + HIDDEN * o], np.zeros(o)]).astype(np.float32)
        assert np.array_equal(w.view(np.uint32), alt.view(np.uint32)), (d, o)
    b64 = base64.b64encode(z.astype("<f8").tobytes()).decode()
    (ROOT / "apps/web/lib/browser/normals.ts").write_text(
        "// Generated by scripts/web_vectors.py: the first standard normals of numpy.random.default_rng(0), little-endian\n"
        "// float64. A job's initial weights are sqrt(2/fan_in) times these (spec initSeed 0), bit for bit.\n"
        f"export const MAX_D_IN = {MAX_D_IN};\nexport const HIDDEN = {HIDDEN};\nexport const MAX_OUT = {MAX_OUT};\n"
        f"export const NORMALS_B64 =\n  \"{b64}\";\n")
    print(f"{len(out)} cases -> {path.relative_to(ROOT)}; {N_NORMALS} normals -> apps/web/lib/browser/normals.ts")


if __name__ == "__main__":
    main()
